// [game_stage.dart] 는 파이널콜에서 사용하는 태블릿 게임의 세부 진행 화면을 구성하는 파일이다.
//
// - [Package] : 파이널콜
// - [TabletScreen] : 태블릿 게임의 세부 진행 화면을 구성함
//
// 즉, 전체 참가자가 게임 단계와 결과를 함께 확인하기 위해 필요한 파일이다.

/// Final Call 태블릿이 실제로 그릴 화면 단계입니다.
///
/// 서버 phase 문자열과 결과 공개 애니메이션 완료 여부를 화면 진입점에서 이
/// enum으로 번역하고, 하위 레이어는 문자열을 다시 해석하지 않습니다.
enum FinalCallTabletStage {
  /// 첫 서버 상태를 기다리며 준비 안내만 표시합니다.
  connecting,

  /// 생존 플레이어 좌석에 카드를 분배합니다.
  dealing,

  /// 중앙 카드·하트·행동 연출을 표시하는 실제 플레이 구간입니다.
  playing,

  /// 제출 카드를 순차 공개하고 점수·하트 손실을 판정합니다.
  roundResult,

  /// 최종 승리 팀과 다시하기/HOME 버튼을 표시합니다.
  result,

  /// 인원 부족 종료 안내를 표시한 뒤 게임 화면을 닫습니다.
  closing,
}
